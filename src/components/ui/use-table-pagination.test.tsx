import { act, cleanup, renderHook, waitFor } from "@testing-library/react"
import { afterEach, describe, expect, it, vi } from "vitest"
import { useClientTablePagination, useRemoteTablePagination, type TablePage } from "./use-table-pagination"
afterEach(cleanup)
const items = Array.from({ length: 76 }, (_, id) => ({ id }))
describe("local table pagination", () => {
  it("filters before paging and resets for equal-length filter results", () => {
    const { result, rerender } = renderHook(({rows, filter}) => useClientTablePagination(rows, filter), {initialProps: {rows: items, filter: "all"}})
    expect(result.current.rows).toHaveLength(25)
    act(() => result.current.pagination.onPageChange(2))
    expect(result.current.rows[0].id).toBe(25)
    const filtered = items.map(row => ({id: row.id + 100}))
    rerender({rows: filtered, filter: "other"})
    expect(result.current.pagination.page).toBe(1)
    expect(result.current.rows[0].id).toBe(100)
  })
  it("clamps after deletions and resets on page-size changes", () => {
    const { result, rerender } = renderHook(({rows}) => useClientTablePagination(rows), {initialProps: {rows: items}})
    act(() => result.current.pagination.onPageChange(4))
    expect(result.current.rows).toEqual([{id: 75}])
    rerender({rows: items.slice(0, 75)})
    expect(result.current.pagination.page).toBe(3)
    rerender({rows: items})
    expect(result.current.pagination.page).toBe(3)
    act(() => result.current.pagination.onPageSizeChange(50))
    expect(result.current.pagination.page).toBe(1)
    expect(result.current.rows).toHaveLength(50)
  })
})
describe("remote table pagination", () => {
  it("passes size and page to the loader without slicing its response", async () => {
    const load = vi.fn(async () => ({rows: [{id: 99}], totalCount: 200}))
    const { result } = renderHook(() => useRemoteTablePagination(load))
    await waitFor(() => expect(result.current.loading).toBe(false))
    act(() => result.current.pagination.onPageChange(2))
    await waitFor(() => expect(load).toHaveBeenLastCalledWith(2, 25))
    await waitFor(() => expect(result.current.loading).toBe(false))
    expect(result.current.rows).toEqual([{id: 99}])
    act(() => result.current.pagination.onPageSizeChange(100))
    await waitFor(() => expect(load).toHaveBeenLastCalledWith(1, 100))
  })
  it("ignores late responses from an old filter query", async () => {
    let resolveOld!: (value: TablePage<{id: number}>) => void
    const oldLoad = vi.fn(() => new Promise<TablePage<{id: number}>>(resolve => {resolveOld = resolve}))
    const newLoad = vi.fn(async () => ({rows: [{id: 2}], totalCount: 1}))
    const { result, rerender } = renderHook(({load}) => useRemoteTablePagination(load), {initialProps: {load: oldLoad as (page: number, size: number) => Promise<TablePage<{id: number}>>}})
    rerender({load: newLoad})
    await waitFor(() => expect(result.current.rows).toEqual([{id: 2}]))
    await act(async () => resolveOld({rows: [{id: 1}], totalCount: 100}))
    expect(result.current.rows).toEqual([{id: 2}])
    expect(result.current.pagination.totalCount).toBe(1)
  })
  it("refetches the last valid page after deletion", async () => {
    const load = vi.fn(async (page: number) => ({rows: [{id: page}], totalCount: 51}))
    const { result } = renderHook(() => useRemoteTablePagination(load))
    await waitFor(() => expect(result.current.loading).toBe(false))
    act(() => result.current.pagination.onPageChange(3))
    await waitFor(() => expect(result.current.rows).toEqual([{id: 3}]))
    load.mockImplementation(async (page: number) => ({rows: [{id: page}], totalCount: 50}))
    act(() => result.current.refresh())
    await waitFor(() => expect(result.current.pagination.page).toBe(2))
    await waitFor(() => expect(result.current.rows).toEqual([{id: 2}]))
  })
  it("reports failures, clears stale results and allows retry", async () => {
    const load = vi.fn(async () => ({rows: [{id: 1}], totalCount: 30}))
    const { result } = renderHook(() => useRemoteTablePagination(load))
    await waitFor(() => expect(result.current.loading).toBe(false))
    load.mockRejectedValueOnce(new Error("offline"))
    act(() => result.current.refresh())
    await waitFor(() => expect(result.current.error).toBeTruthy())
    expect(result.current.rows).toEqual([])
    expect(result.current.pagination.disabled).toBe(true)
    act(() => result.current.refresh())
    await waitFor(() => expect(result.current.error).toBeNull())
    await waitFor(() => expect(result.current.rows).toEqual([{id: 1}]))
  })
})
